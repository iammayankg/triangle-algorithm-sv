"""Emit the BPCG / corrective-FW comparison table of the journal draft
(tab:bpcg) as a complete LaTeX table environment, so the numbers cannot
drift from the result files:

  results/step_profile5.json     block ETA (k=16) and BPCG on product atoms,
                                 isolated October runs
  results/step_profile_cfw.json  BPCG on side supports, the QC-MNP hybrid and
                                 fully-corrective FW (src/corrective_fw.py),
                                 same protocol (2026-10-13 review)
  results/bpcg_baseline.json     gisette KL2, September, concurrent run
  results/step_profile_bpcg2.json  if present: both BPCGs on every cell and
                                 block ETA on gisette KL2 after the
                                 kernel-column fix of 2026-10-14; its rows
                                 replace the older ones for the same
                                 (cell, solver), and the September rows are
                                 dropped once it has gisette KL2

Usage: python3 src/bpcg_table.py > paper/aor/tab_bpcg.tex
"""
import json
from pathlib import Path

import numpy as np
from scipy import stats

R = Path(__file__).resolve().parents[1] / 'results'
CELLS = [('gisette-l2', r'gisette $L_2$, $C{=}1$'),
         ('gisette-kl2', r'gisette KL2$^\dagger$'),
         ('w8a-kl2', 'w8a KL2'), ('a9a-kl2', 'a9a KL2'),
         ('covtype-kl2', 'covtype KL2'), ('ijcnn1-kl2', 'ijcnn1 KL2')]
SOLVERS = [('block16', 'ETA, $k{=}16$'), ('bpcg', 'BPCG, product atoms'),
           ('bpcg-side', 'BPCG, side supports'), ('cfw-qcmnp', 'CFW, QC-MNP'),
           ('fcfw', 'FCFW')]
SEPT = {'eta': 'block16', 'bpcg': 'bpcg'}


def ci95(xs):
    xs = np.asarray(xs, dtype=float)
    if len(xs) < 2:
        return float(xs.mean()), 0.0
    return float(xs.mean()), float(stats.t.ppf(0.975, len(xs) - 1)
                                   * xs.std(ddof=1) / np.sqrt(len(xs)))


def fmt_time(rs):
    conv = [r for r in rs if r['status'] == 'converged']
    if len(conv) < len(rs):
        return r'$>600$' if not conv else r'$>600^\ast$'
    m, h = ci95([r['time'] for r in rs])
    return (r'$%.0f\pm%.0f$' if m >= 100 else r'$%.1f\pm%.1f$') % (m, h)


def fmt_gap(rs):
    capped = [r['gap'] for r in rs if r['status'] != 'converged']
    if not capped:
        return r'$\le10^{-3}$'
    lo, hi = min(capped), max(capped)
    f = (lambda g: f'{g:.2f}' if g >= 0.1 else f'{g:.2g}')
    return f'{f(lo)}' if f(lo) == f(hi) else f'{f(lo)}--{f(hi)}'


def mean_int(rs, key):
    return f"{int(round(np.mean([r[key] for r in rs]))):,}"


def main():
    oct_ = json.load(open(R / 'step_profile5.json'))
    cfw = json.load(open(R / 'step_profile_cfw.json'))
    sept = [dict(r, solver=SEPT[r['solver']])
            for r in json.load(open(R / 'bpcg_baseline.json'))
            if r['cell'] == 'gisette-kl2']
    rows = oct_ + cfw
    fix = R / 'step_profile_bpcg2.json'
    if fix.exists():
        new = json.load(open(fix))
        keys = {(r['cell'], r['solver']) for r in new}
        rows = [r for r in rows if (r['cell'], r['solver']) not in keys] + new
        if not any(r['cell'] == 'gisette-kl2' for r in new):
            rows += sept
    else:
        rows += sept
    out = [r"% generated by src/bpcg_table.py from results/step_profile5.json, "
           r"results/step_profile_cfw.json and results/bpcg_baseline.json; do not edit",
           r"\begin{table}[htbp]\centering\scriptsize\setlength{\tabcolsep}{3pt}",
           r"\caption{Block ETA ($k{=}16$) against BPCG \citep{tsuji2022} and "
           r"corrective FW \citep{halbey2025} on the same objective with the same "
           r"certificate ($\varepsilon{=}10^{-3}$), the same column cache and the same "
           r"600\,s cap: the isolated runs of Table~\ref{tab:kreal} (three seeds, "
           r"each configuration alone in a fresh process, AMD EPYC 7B13; "
           r"\texttt{src/step\_profile.py}), and for gisette KL2, which those runs "
           r"do not include, the September run (\texttt{src/bpcg\_baseline.py}, "
           r"three seeds, concurrent with the regime battery on the earlier "
           r"machine), marked $^\dagger$. BPCG on product atoms is "
           r"\texttt{src/bpcg.py}; BPCG on side supports, CFW with QC-MNP "
           r"corrections and fully-corrective FW (FCFW) are Algorithm~1 of "
           r"\citet{halbey2025} on the product of the two simplices with the local "
           r"pairwise step, the QC-MNP hybrid (a correction whenever a new atom "
           r"has entered) and full correction (\texttt{src/corrective\_fw.py}). "
           r"Columns are kernel or Gram columns computed; drops count removed "
           r"support indices (ETA: away drops; BPCG: capped local steps; CFW, "
           r"FCFW: indices zeroed by truncations or local steps). Gap = certified "
           r"relative gap at the 600\,s cap where a run stopped there; "
           r"$^\ast$ one of three seeds converged within the cap (597\,s), the gap is "
           r"over the other two. Where runs converged, distances agree per cell and "
           r"seed to $10^{-6}$ and test accuracies to $2\times10^{-4}$.}\label{tab:bpcg}",
           r"\begin{tabular}{llrrrrl}\toprule",
           r"cell & solver & time (s) & iterations & columns & drops & gap \\\midrule"]
    for cell, clab in CELLS:
        for solver, slab in SOLVERS:
            rs = [r for r in rows if r['cell'] == cell and r['solver'] == solver]
            if not rs:
                continue
            out.append(f"{clab} & {slab} & {fmt_time(rs)} & {mean_int(rs, 'iters')} & "
                       f"{mean_int(rs, 'oracle')} & {mean_int(rs, 'n_drops')} & "
                       f"{fmt_gap(rs)} \\\\")
        out.append(r"\midrule")
    out[-1] = r"\bottomrule"
    out.append(r"\end{tabular}\end{table}")
    print("\n".join(out))


if __name__ == '__main__':
    main()
