"""Dataset table of the journal draft (tab:datasets): training and test
sizes, dimension, positive-class fraction and density of the LIBSVM sets as
loaded by src/full_battery.py (covtype: the seed-0 split, training part
subsampled to 100,000).  Writes paper/aor/tab_datasets.tex.

Usage: python3 src/dataset_table.py --data-dir data
"""
import argparse, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parent))
from full_battery import _load_cached, DATASETS

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data-dir', default='data')
    ap.add_argument('--out', default='paper/aor/tab_datasets.tex')
    a = ap.parse_args()
    out = [r"% generated by src/dataset_table.py; do not edit",
           r"\begin{table}[htbp]\centering\scriptsize",
           r"\caption{Datasets (LIBSVM binary sets, features standardised on the training part). covtype is the class-2-versus-rest binary set, split 75/25 by seed with the training part subsampled to $100{,}000$; kernel cells use a class-balanced subsample of the training part (Section~\ref{app:details}).}\label{tab:datasets}",
           r"\begin{tabular}{lrrrrr}\toprule",
           r"dataset & $n+m$ (train) & test & $d$ & positive fraction & nonzeros \\\midrule"]
    for name in ('gisette', 'a9a', 'w8a', 'ijcnn1', 'covtype'):
        X, y, Xt, yt = _load_cached(name, a.data_dir, 100_000, 0)
        pos = float(np.mean(y == 1)); nz = float(np.mean(X != 0))
        out.append(f"{name} & {len(X):,} & {len(Xt):,} & {X.shape[1]:,} & {pos:.3f} & {nz:.2f} \\\\")
    out += [r"\bottomrule", r"\end{tabular}\end{table}"]
    Path(a.out).write_text("\n".join(out) + "\n"); print('wrote', a.out)

if __name__ == '__main__':
    main()
